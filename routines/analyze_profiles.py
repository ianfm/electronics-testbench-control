#!/usr/bin/env python3
"""Battery Cell Characterization and Profiling Analyzer.

Parses CSV logs generated by the M300 battery balancer to construct capacity (Ah)
and DC Internal Resistance (IR) profiles, outputs a markdown report, and optionally
plots the charge curves.
"""

import argparse
import csv
import glob
import os
import sys
import time
from typing import Dict, List, Tuple

# Optional plotting library
try:
    import matplotlib.pyplot as plt
    HAS_MATPLOTLIB = True
except ImportError:
    HAS_MATPLOTLIB = False


def find_latest_log(log_dir: str) -> str | None:
    """Finds the most recent balancer CSV log file in log_dir."""
    if not os.path.exists(log_dir):
        return None
    files = glob.glob(os.path.join(log_dir, "balancer_log_*.csv"))
    if not files:
        return None
    return max(files, key=os.path.getmtime)


def parse_balancer_log(filepath: str) -> Tuple[List[str], Dict[str, List]]:
    """Parses the balancer log into lists of times and cell data arrays."""
    data = {
        "timestamps": [],
        "b1_status": [],
        "b1_charge_mode": [],
        "b1_psu_v": [],
        "b1_psu_i": [],
        "b2_status": [],
        "b2_charge_mode": [],
        "b2_psu_v": [],
        "b2_psu_i": [],
        "v_cells": {c: [] for c in range(1, 17)},
        "i_cells": {c: [] for c in range(1, 17)},
        "ir_cells": {c: [] for c in range(1, 17)},
        "ah_cells": {c: [] for c in range(1, 17)},
    }

    with open(filepath, "r", newline="") as f:
        reader = csv.reader(f)
        headers = next(reader)
        
        # Verify columns count (should be at least 73 columns)
        if len(headers) < 73:
            print(f"Warning: CSV has {len(headers)} columns, expected 73. Continuing with fallback parsing.")
            
        for row in reader:
            if not row:
                continue
            try:
                # Basic fields
                data["timestamps"].append(row[0])
                data["b1_status"].append(row[1])
                data["b1_charge_mode"].append(row[2])
                data["b1_psu_v"].append(float(row[3]))
                data["b1_psu_i"].append(float(row[4]))
                data["b2_status"].append(row[5])
                data["b2_charge_mode"].append(row[6])
                data["b2_psu_v"].append(float(row[7]))
                data["b2_psu_i"].append(float(row[8]))
                
                # Cell voltages (cols 9-24)
                for c in range(1, 17):
                    data["v_cells"][c].append(float(row[8 + c]))
                
                # Cell currents (cols 25-40)
                for c in range(1, 17):
                    data["i_cells"][c].append(float(row[24 + c]))
                
                # Cell IR (cols 41-56)
                for c in range(1, 17):
                    # Check if IR data exists in this row
                    val = float(row[40 + c]) if len(row) > 40 + c else 0.0
                    data["ir_cells"][c].append(val)
                
                # Cell Ah (cols 57-72)
                for c in range(1, 17):
                    val = float(row[56 + c]) if len(row) > 56 + c else 0.0
                    data["ah_cells"][c].append(val)
                    
            except (ValueError, IndexError) as e:
                # Skip corrupt/empty rows silently
                continue

    return data["timestamps"], data


def analyze_cell_profiles(timestamps: List[str], data: Dict) -> Dict:
    """Computes key characterization metrics for each battery cell."""
    analysis = {}
    num_steps = len(timestamps)
    if num_steps < 2:
        return analysis

    # Parse time differences to estimate charge durations
    time_format = "%Y-%m-%dT%H:%M:%S"
    try:
        # Strip off milliseconds if present in ISO 8601 format
        t0 = timestamps[0].split(".")[0]
        t1 = timestamps[-1].split(".")[0]
        t_start = time.strptime(t0, time_format)
        t_end = time.strptime(t1, time_format)
        duration_sec = time.mktime(t_end) - time.mktime(t_start)
    except Exception:
        # Fallback if timestamp format differs
        duration_sec = num_steps * 5.0  # Assumes 5s average step if parsing fails
        
    for c in range(1, 17):
        voltages = data["v_cells"][c]
        currents = data["i_cells"][c]
        irs = [r for r in data["ir_cells"][c] if r > 0.0]
        ahs = data["ah_cells"][c]

        if not voltages:
            continue

        v_init = voltages[0]
        v_final = voltages[-1]
        v_max = max(voltages)
        
        # Max capacity is final accumulated Ah value
        ah_delivered = ahs[-1] if ahs else 0.0
        
        # Get converged IR (average of the last 3 valid estimates to ensure settling)
        ir_converged = sum(irs[-3:]) / len(irs[-3:]) if irs else 0.0
        ir_min = min(irs) if irs else 0.0
        ir_max = max(irs) if irs else 0.0
        
        # Average charging current when active (> 50mA)
        active_currents = [i for i in currents if i > 0.05]
        avg_active_current = sum(active_currents) / len(active_currents) if active_currents else 0.0

        analysis[c] = {
            "v_init": v_init,
            "v_final": v_final,
            "v_max": v_max,
            "ah_delivered": ah_delivered,
            "ir_converged": ir_converged,
            "ir_min": ir_min,
            "ir_max": ir_max,
            "avg_current": avg_active_current,
        }

    return {
        "duration_sec": duration_sec,
        "cell_metrics": analysis,
    }


def print_ascii_summary(duration: float, metrics: Dict[int, Dict]) -> None:
    """Prints a beautiful ASCII table summarizing the cell health metrics."""
    hours = int(duration // 3600)
    minutes = int((duration % 3600) // 60)
    seconds = int(duration % 60)
    
    print("\n" + "=" * 80)
    print(f" CELL CHARACTERIZATION SUMMARY (Test Duration: {hours:02d}:{minutes:02d}:{seconds:02d})")
    print("=" * 80)
    print(f"| Cell | Init V | Final V | Max V  | Delivered | Converged IR | Avg Current |")
    print(f"|  #   |  (V)   |   (V)   |  (V)   |   (mAh)   |    (mΩ)      |     (A)     |")
    print("-" * 80)
    
    for c, m in sorted(metrics.items()):
        v_init = f"{m['v_init']:.4f} V"
        v_final = f"{m['v_final']:.4f} V"
        v_max = f"{m['v_max']:.4f} V"
        capacity = f"{m['ah_delivered'] * 1000.0:7.1f} mAh"
        ir = f"{m['ir_converged'] * 1000.0:6.1f} mΩ" if m['ir_converged'] > 0 else "  --  mΩ"
        avg_i = f"{m['avg_current']:.3f} A"
        print(f"|  {c:02d}  | {v_init} | {v_final} | {v_max} | {capacity} | {ir:12s} | {avg_i:11s} |")
        
    print("=" * 80)


def generate_markdown_report(filepath: str, duration: float, metrics: Dict[int, Dict]) -> str:
    """Generates a detailed markdown report file containing cell characterizations."""
    base_name = os.path.basename(filepath)
    report_path = filepath.replace(".csv", "_report.md")
    
    hours = int(duration // 3600)
    minutes = int((duration % 3600) // 60)
    
    # Calculate statistics
    capacities = [m["ah_delivered"] * 1000.0 for m in metrics.values()]
    irs = [m["ir_converged"] * 1000.0 for m in metrics.values() if m["ir_converged"] > 0]
    
    avg_cap = sum(capacities) / len(capacities) if capacities else 0.0
    min_cap = min(capacities) if capacities else 0.0
    max_cap = max(capacities) if capacities else 0.0
    cap_spread = max_cap - min_cap
    
    avg_ir = sum(irs) / len(irs) if irs else 0.0
    min_ir = min(irs) if irs else 0.0
    max_ir = max(irs) if irs else 0.0
    ir_spread = max_ir - min_ir

    cap_dev_str = f"({(cap_spread / avg_cap) * 100:.1f}% deviation)" if avg_cap > 0 else "N/A"
    ir_dev_str = f"({(ir_spread / avg_ir) * 100:.1f}% deviation)" if avg_ir > 0 else "N/A"

    with open(report_path, "w") as f:
        f.write(f"# LiFePO4 Cell Characterization and Profiling Report\n\n")
        f.write(f"**Source Log:** `{base_name}`  \n")
        f.write(f"**Analysis Date:** {time.strftime('%Y-%m-%d %H:%M:%S')}  \n")
        f.write(f"**Charge Duration:** {hours}h {minutes}m  \n\n")
        
        f.write(f"## Batch Statistical Health Indicators\n\n")
        f.write(f"| Parameter | Average | Minimum | Maximum | Spread / Delta |\n")
        f.write(f"|---|---|---|---|---|\n")
        f.write(f"| **Capacity (mAh)** | {avg_cap:.1f} mAh | {min_cap:.1f} mAh | {max_cap:.1f} mAh | {cap_spread:.1f} mAh {cap_dev_str} |\n")
        f.write(f"| **Internal Resistance (mΩ)** | {avg_ir:.1f} mΩ | {min_ir:.1f} mΩ | {max_ir:.1f} mΩ | {ir_spread:.1f} mΩ {ir_dev_str} |\n\n")
        
        f.write(f"## Individual Cell Health Assessment\n\n")
        f.write(f"| Cell | Initial OCV (V) | Final OCV (V) | Capacity (mAh) | DC IR (mΩ) | Health Evaluation |\n")
        f.write(f"|---|---|---|---|---|---|\n")
        
        for c, m in sorted(metrics.items()):
            ir_val = m["ir_converged"] * 1000.0
            cap_val = m["ah_delivered"] * 1000.0
            
            # Simple heuristic cell rules
            issues = []
            if ir_val > 15.0:
                issues.append("High DC IR (potential degradation or contact resistance)")
            if ir_val > 0.0 and ir_val < 3.0:
                issues.append("Suspiciously low DC IR (verify connections)")
            if cap_val < avg_cap * 0.90:
                issues.append("Low Capacity (<90% of batch average)")
            if m["v_final"] < 3.35:
                issues.append("Undercharged / relaxation drop below plateau")
                
            status = ", ".join(issues) if issues else "Healthy"
            ir_str = f"{ir_val:.1f} mΩ" if ir_val > 0 else "N/A"
            f.write(f"| Cell {c:02d} | {m['v_init']:.4f} V | {m['v_final']:.4f} V | {cap_val:.1f} mAh | {ir_str} | **{status}** |\n")
            
        f.write(f"\n## Profile Explanatory Notes\n\n")
        f.write(f"- **DC Internal Resistance (IR)** is estimated via transient step responses ($\Delta V / \Delta I$) immediately when the balancer halts charging to perform Open-Circuit Voltage measurements.\n")
        f.write(f"- **Capacity (mAh)** is integrated via continuous Coulomb counting (Riemann sum) mapped to specific cell charging slots.\n")
        f.write(f"- LiFePO4 cells of 1350 mAh should typically converge to **5-12 mΩ** internal resistance depending on terminal contacts, cabling, and temperature.\n")
        
    return report_path


def generate_profile_plots(filepath: str, timestamps: List[str], data: Dict) -> str | None:
    """Generates three subplots showing cell voltage, capacity, and IR trends over time."""
    if not HAS_MATPLOTLIB:
        return None
        
    fig, axes = plt.subplots(3, 1, figsize=(10, 12), sharex=True)
    plot_path = filepath.replace(".csv", "_profile.png")
    
    steps = list(range(len(timestamps)))
    
    # 1. Voltage Profile
    for c in range(1, 17):
        axes[0].plot(steps, data["v_cells"][c], label=f"Cell {c:02d}" if c in [1, 8, 9, 16] else "")
    axes[0].set_ylabel("Cell Voltage (V)")
    axes[0].set_title("16-Channel LiFePO4 Voltage Profiles")
    axes[0].grid(True, linestyle="--", alpha=0.6)
    axes[0].legend(loc="upper left")
    
    # 2. Accumulated Capacity Profile
    for c in range(1, 17):
        axes[1].plot(steps, [ah * 1000.0 for ah in data["ah_cells"][c]], label=f"Cell {c:02d}" if c in [1, 8, 9, 16] else "")
    axes[1].set_ylabel("Capacity Delivered (mAh)")
    axes[1].set_title("Delivered Energy (Coulomb Count)")
    axes[1].grid(True, linestyle="--", alpha=0.6)
    
    # 3. DC Internal Resistance Profile
    for c in range(1, 17):
        # Only plot non-zero IR points
        c_ir = [ir * 1000.0 for ir in data["ir_cells"][c]]
        # Filter for step index where IR > 0
        filtered_steps = [s for s, r in zip(steps, c_ir) if r > 0.0]
        filtered_ir = [r for r in c_ir if r > 0.0]
        if filtered_steps:
            axes[2].scatter(filtered_steps, filtered_ir, marker="o", s=25, label=f"Cell {c:02d}" if c in [1, 8, 9, 16] else "")
            axes[2].plot(filtered_steps, filtered_ir, alpha=0.4)
            
    axes[2].set_ylabel("Internal Resistance (mΩ)")
    axes[2].set_xlabel("Time step")
    axes[2].set_title("DC Internal Resistance Trends (Step Response)")
    axes[2].grid(True, linestyle="--", alpha=0.6)
    
    plt.tight_layout()
    plt.savefig(plot_path, dpi=150)
    plt.close()
    return plot_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Battery Cell Profiler and Report Generator")
    parser.add_argument("csv_file", nargs="?", help="Path to balancer CSV log file")
    parser.add_argument("--log-dir", default="logs", help="Directory to search if no CSV path is provided")
    args = parser.parse_args()

    csv_path = args.csv_file
    if not csv_path:
        csv_path = find_latest_log(args.log_dir)
        if not csv_path:
            print(f"Error: No log file specified, and no log file found in '{args.log_dir}'.")
            sys.exit(1)
            
    print(f"Analyzing battery telemetry: {csv_path}")
    if not os.path.exists(csv_path):
        print(f"Error: File '{csv_path}' does not exist.")
        sys.exit(1)
        
    timestamps, data = parse_balancer_log(csv_path)
    analysis = analyze_cell_profiles(timestamps, data)
    
    if not analysis:
        print("Error: No data rows could be parsed. Verify the CSV log content.")
        sys.exit(1)
        
    print_ascii_summary(analysis["duration_sec"], analysis["cell_metrics"])
    
    report_path = generate_markdown_report(csv_path, analysis["duration_sec"], analysis["cell_metrics"])
    print(f"Generated Markdown health report: {report_path}")
    
    plot_path = generate_profile_plots(csv_path, timestamps, data)
    if plot_path:
        print(f"Generated profile chart: {plot_path}")
    else:
        print("Matplotlib not found; skipping profile plotting (run 'pip install matplotlib' to enable).")


if __name__ == "__main__":
    main()
